// Writes src/lib/footer-case-links.ts: the footer's case links (slug, format,
// sphere) as a tiny static list, so the footer on every page doesn't pull in
// the whole showcase data file. Run after changing showcase cases:
//   npx tsx --tsconfig tsconfig.json scripts/gen-footer-cases.ts
import { writeFileSync } from "node:fs";
import { visibleShowcaseItems } from "../src/lib/showcase-data";

// short labels: no parentheses, the first part of "a / b" spheres
const tidy = (l: Record<string, string>, first = false) =>
  Object.fromEntries(Object.entries(l).map(([k, v]) => {
    let t = v.replace(/\s*[(（][^)）]*[)）]/g, "").trim();
    if (first) t = t.split(/\s*\/\s*/)[0];
    return [k, t];
  })) as typeof l;
const items = visibleShowcaseItems.filter((c) => c.status !== "concept").slice(0, 10).map((c) => ({ slug: c.slug, format: tidy(c.format), sphere: tidy(c.sphere, true) }));
const body = `// Generated by scripts/gen-footer-cases.ts — do not edit by hand.
import type { L } from "@/lib/i18n-text";

export const FOOTER_CASE_LINKS: { slug: string; format: L; sphere: L }[] = ${JSON.stringify(items, null, 2)};
`;
writeFileSync("src/lib/footer-case-links.ts", body);
console.log(items.length, "case links");
